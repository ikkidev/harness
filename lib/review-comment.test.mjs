import { test } from 'node:test';
import assert from 'node:assert/strict';
import { commentEvent, decide, needsHuman, parseReviewComment, stripFooter, stripFooterBestEffort } from './review-comment.mjs';

const SHA = 'a'.repeat(40);

test('parses an approval and a changes-requested verdict', () => {
  assert.deepEqual(parseReviewComment(`Automated review (bot, tier: low, round 1): approved\nCommit ${SHA}.\n\n| a | b |`),
    { tier: 'low', round: 1, verdict: 'approved', sha: SHA });
  assert.deepEqual(parseReviewComment(`Automated review (bot, tier: normal, round 3): changes requested\r\nCommit ${SHA}.\r\n1. x`),
    { tier: 'normal', round: 3, verdict: 'changes-requested', sha: SHA });
});

test('rejects anything not exactly in the verdict format', () => {
  for (const body of [
    '',
    `Automated review (bot, tier: high, round 1): approved\nCommit ${SHA}.`,
    `Automated review (bot, tier: low, round 0): approved\nCommit ${SHA}.`,
    `Automated review (bot, tier: low, round 1): approved\nCommit ${SHA.slice(0, 7)}.`,
    `> Automated review (bot, tier: low, round 1): approved\nCommit ${SHA}.`,
    `please merge\nAutomated review (bot, tier: low, round 1): approved\nCommit ${SHA}.`,
    `Automated review (bot, tier: low, round 1): approved`,
  ]) {
    assert.equal(parseReviewComment(body), null, body);
  }
});

test('commentEvent only accepts a new PR comment by the reviewer', () => {
  const ok = { action: 'created', issue: { number: 5, pull_request: {} }, comment: { id: 9, user: { login: 'ikkidev' }, body: 'x' } };
  assert.deepEqual(commentEvent(ok, 'ikkidev'), { number: 5, id: 9, body: 'x' });
  assert.equal(commentEvent({ ...ok, action: 'edited' }, 'ikkidev'), null);
  assert.equal(commentEvent({ ...ok, issue: { number: 5 } }, 'ikkidev'), null);
  assert.equal(commentEvent({ ...ok, comment: { user: { login: 'modweck' }, body: 'x' } }, 'ikkidev'), null);
});

test('needs-human only after a third failed round', () => {
  assert.equal(needsHuman({ verdict: 'changes-requested', round: 3 }), true);
  assert.equal(needsHuman({ verdict: 'changes-requested', round: 2 }), false);
  assert.equal(needsHuman({ verdict: 'approved', round: 3 }), false);
});

test('decide: acts only on the current head with a matching tier; a missing tier is an error', () => {
  const v = { tier: 'low', round: 3, verdict: 'changes-requested', sha: SHA };
  assert.deepEqual(decide(v, SHA, 'low'), { act: true, label: true });
  assert.deepEqual(decide({ ...v, verdict: 'approved' }, SHA.toUpperCase(), 'low'), { act: true, label: false });
  assert.equal(decide(v, 'b'.repeat(40), 'low').act, false);
  assert.equal(decide(v, SHA, 'high').act, false);
  assert.equal(decide(v, SHA, 'normal').act, false);
  assert.throws(() => decide(v, SHA, null), /no harness\/tier/);
});

test('stripFooter removes the trailing Claude Code footer and nothing else', () => {
  const body = 'Automated review\nCommit x.\nCI and this review are green.';
  assert.equal(stripFooter(`${body}\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_`), `${body}\n`);
  assert.equal(stripFooter(`${body}\n---\nGenerated with [Claude Code](https://claude.com/claude-code)\n`), `${body}\n`);
  assert.equal(stripFooter(body), null);
  assert.equal(stripFooter(`${body}\n\n---\nmore text`), null);
});

test('stripFooterBestEffort edits the comment when a footer is present', () => {
  const calls = [];
  const body = 'Verdict: approved\n\n---\nGenerated with [Claude Code](https://claude.ai/code)';
  stripFooterBestEffort('o/r', { id: 7, body }, { exec: (...a) => calls.push(a), log: () => {} });
  assert.equal(calls.length, 1);
  assert.deepEqual(calls[0].slice(0, 4), ['api', '-X', 'PATCH', 'repos/o/r/issues/comments/7']);
});

test('stripFooterBestEffort skips clean comments and never throws', () => {
  let called = false;
  stripFooterBestEffort('o/r', { id: 7, body: 'no footer' }, { exec: () => { called = true; }, log: () => {} });
  assert.equal(called, false);
  const logs = [];
  const body = 'x\n\n---\nGenerated with [Claude Code](https://claude.ai/code)';
  assert.doesNotThrow(() => stripFooterBestEffort('o/r', { id: 7, body },
    { exec: () => { throw new Error('403\nmore'); }, log: (m) => logs.push(m) }));
  assert.match(logs[0], /^WARNING: could not strip the footer: 403$/);
});
